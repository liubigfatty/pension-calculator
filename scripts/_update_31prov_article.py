# 表格整体替换：定位 "| 1 | 上海 |" 起，到 "| 31 | 河南 |" 行止
def replace_table(text):
    lines = text.split('\n')
    start = next((i for i, l in enumerate(lines) if l.startswith('| 1 | 上海 |')), None)
    end = next((i for i, l in enumerate(lines) if l.startswith('| 31 | 河南 |')), None)
    if start is None or end is None:
        return text, '表格定位失败'
    new = lines[:start] + NEW_TABLE.split('\n') + lines[end + 1:]
    return '\n'.join(new), '表格已替换(%d 行→%d 行)' % (end - start + 1, len(NEW_TABLE.split('\n')))


