// 居民 vs 职工：增长机制的跨省对比（普适层）
const f=(n,p=2)=>Number(n.toFixed(p));

console.log('=== ① 职工养老金 21 连涨 复利累计（全国口径）===');
const staff=[['2006',23.7],['2007',9.1],['2008',10],['2009',10],['2010',10],['2011',10],
['2012',10],['2013',10],['2014',10],['2015',10],['2016',6.5],['2017',5.5],
['2018',5],['2019',5],['2020',5],['2021',4.5],['2022',4.0],['2023',3.8],['2024',3.0],['2025',2.0]];
let acc=1; staff.forEach(([y,r])=>acc*= (1+r/100));
console.log('2006-2025 累计倍数  ', f(acc,4), '倍   累计涨幅', f((acc-1)*100,1)+'%');
console.log('年均复合            ', f((Math.pow(acc,1/20)-1)*100,2)+'%');

console.log('\n=== ② 居民基础养老金（中央最低标准）===');
const res=[['2009',55],['2014',70],['2018',88],['2020',93],['2022',98],['2023',103],['2024',123],['2025',143],['2026',163]];
res.forEach(([y,v],i)=>{
  const pv= i? res[i-1][1]:null;
  console.log(y, String(v).padStart(4)+'元', pv? '  +'+(v-pv)+'元  (+'+f((v/pv-1)*100,2)+'%)':'');
});
console.log('2009-2026 累计涨幅  ', f((163/55-1)*100,1)+'%   倍数', f(163/55,3));
console.log('年均复合(17年)      ', f((Math.pow(163/55,1/17)-1)*100,2)+'%');

console.log('\n=== ③ 机制差：定额 vs 比例（关键）===');
console.log('职工调整 = 本人养老金 × r（挂钩）→ 指数增长');
console.log('居民调整 = 固定金额 +d（普惠）  → 等差增长');
const r=0.02, d=20;
const cross = d/r;
console.log('\n分界点：月养老金 =', f(cross,0), '元');
console.log('  → 低于', f(cross,0), '元：职工每年涨的钱 < 居民每年涨的 20 元');
console.log('  → 高于', f(cross,0), '元：职工每年涨的钱 > 居民每年涨的 20 元');

console.log('\n=== ④ 未来 20 年路径（假设职工年均 2%、居民年均 +20 元）===');
const rows=[['武汉·职工60档',1609],['武汉·居民顶格',989],['吉林·职工60档',1384.8],['吉林·居民顶格',905.9]];
rows.forEach(([nm,p0])=>{
  const isStaff = nm.includes('职工');
  let p=p0, sum=0;
  for(let i=0;i<20;i++){ sum += p*12; p = isStaff? p*(1+r) : p+d; }
  console.log(nm.padEnd(16), '起', String(f(p0,1)).padStart(7), '→ 20年后', String(f(p,1)).padStart(7),
    '  20年累计领取', f(sum/10000,2)+'万', '  月增额', f(isStaff? p0*r : d,1));
});

console.log('\n=== ⑤ 职工"多缴多得"是终身复利（武汉例）===');
[1000,1609,2000,3000].forEach(p0=>{
  const p20=p0*Math.pow(1+r,20);
  console.log('月领'+String(p0).padStart(5)+'元 → 20年后'+String(f(p20,1)).padStart(7)+'元  累计多领'+String(f((p20-p0)*12*20/10000,2)).padStart(6)+'万');
});
