/**
 * 生成云函数 calculate 的「单文件省份配置」：cloudfunctions/calculate/provinces-data.js
 *
 * 为什么需要它（2026-09-09 线上事故）：
 *   微信开发者工具 CLI 部署云函数时**不会把子目录一起传上去**，
 *   导致云端 require('./provinces/beijing.js') 直接报
 *   "Cannot find module './provinces/beijing.js'"（Require stack: /var/user/index.js）。
 *   旁证：index-mini 的 calcIndex 用的就是单文件 provinces-data.js，一直正常。
 *   故把 31 个省模块内联进一个文件，彻底绕开子目录问题。
 *
 * 真相源：cloudfunctions/calculate/provinces/*.js（31 个省，无 require/window/import，可安全内联）
 *
 * 用法：改完任何省份配置后必须重跑
 *   node scripts/build-cloud-provinces.js
 */
const fs = require('fs')
const path = require('path')

const ROOT = path.resolve(__dirname, '..')
const SRC_DIR = path.join(ROOT, 'cloudfunctions', 'calculate', 'provinces')
const OUT = path.join(ROOT, 'cloudfunctions', 'calculate', 'provinces-data.js')

const files = fs.readdirSync(SRC_DIR).filter(f => f.endsWith('.js')).sort()

if (files.length !== 31) {
  console.warn(`[warn] 期望 31 个省文件，实际 ${files.length} 个：${files.join(', ')}`)
}

const chunks = []
chunks.push(`// AUTO-GENERATED by scripts/build-cloud-provinces.js — 请勿手改
// 真相源：cloudfunctions/calculate/provinces/*.js（共 ${files.length} 个省）
//
// ⚠️ 为什么是单文件：微信开发者工具 CLI 部署云函数**不上传子目录**，
//    云端 require('./provinces/xx.js') 会报 Cannot find module（2026-09-09 事故）。
//    改完省份配置后必须重跑：node scripts/build-cloud-provinces.js
//
// 生成时间：${new Date().toISOString()}

const _CONFIGS = {}
function _register(name, cfg) { _CONFIGS[name] = cfg }

`)

for (const f of files) {
  const name = path.basename(f, '.js')
  const src = fs.readFileSync(path.join(SRC_DIR, f), 'utf8')
  // 每个省包一层 IIFE：
  //   - var module/exports 遮蔽外层，省份源码里的 module.exports = {...} 落到内部对象
  //   - 各省顶层 const 同名（PROV_BASE 等）互不冲突
  chunks.push(`// ================= ${name} =================
;(function () {
  var module = { exports: {} }
  var exports = module.exports
${src}
  var __cfg = (typeof getEngineConfig === 'function') ? getEngineConfig() : module.exports.getEngineConfig()
  _register('${name}', __cfg)
})()

`)
}

chunks.push(`module.exports = {
  PROVINCE_CONFIGS: _CONFIGS,
  getConfig: function (province) { return _CONFIGS[province] || null },
  listProvinces: function () { return Object.keys(_CONFIGS) },
}
`)

fs.writeFileSync(OUT, chunks.join(''), 'utf8')

const sizeKb = (fs.statSync(OUT).size / 1024).toFixed(1)
console.log(`[ok] 已生成 ${path.relative(ROOT, OUT)}（${files.length} 省，${sizeKb} KB）`)

// 自检：逐省取一次 getEngineConfig，确保没有语法/运行时错误
const { listProvinces, getConfig } = require(OUT)
const names = listProvinces()
let bad = 0
for (const p of names) {
  try {
    const c = getConfig(p)
    if (!c || typeof c !== 'object') throw new Error('配置非对象')
  } catch (e) {
    bad++
    console.error(`[fail] ${p}: ${e.message}`)
  }
}
console.log(bad === 0
  ? `[ok] 自检通过：${names.length}/${names.length} 省配置可正常加载`
  : `[fail] 自检失败：${bad}/${names.length} 省异常`)
process.exit(bad === 0 ? 0 : 1)
