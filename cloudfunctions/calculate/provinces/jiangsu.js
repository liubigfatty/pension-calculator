// 计发基数预测函数（江苏省专用）
function predictBase(year) {
  const BASE = PROV_BASE
  const bp = BASE_PARAMS
  const lastYear = 2025
  const lastVal  = BASE[lastYear] || 8917
  if (year <= lastYear) return BASE[year] || 0
  return Math.round(lastVal * Math.pow(1 + bp.PROV_GROWTH, year - lastYear))
}

